"""Frozen BERT, layer by layer: how well does each layer's embedding predict text difficulty?

For every layer (0 = embedding layer, 1..12 = transformer layers) and for the mean of layers 1-12, a ridge regression is fitted on the embeddings of the
training texts (alpha chosen by leave-one-out cross-validation on the training texts) and graded on the 865 real-Finnish test texts, exactly as in the
curated experiments. Both training sets: the real-Finnish train texts, and all train texts. Needs the cached embeddings (python bert_based/embeddings.py).

    python bert_based/run_layers.py                      writes bert_based/reports/BERT_LAYERS.md
"""
import argparse
import sys
from pathlib import Path

import numpy as np
from sklearn.linear_model import RidgeCV
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # repo root
from bert_based import embeddings  # noqa: E402
from core import predictions  # noqa: E402
from core.dataset import TRAIN_SETS, load_split, train_mask  # noqa: E402
from core.evaluate import bootstrap_mae, ci, metrics  # noqa: E402
from core.reporting import confusion_md, pct, steps, table  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "bert_based" / "reports" / "BERT_LAYERS.md"
CURATED_RUNS = ROOT / "curated_features" / "modeling" / "reports" / "runs"
CURATED_CONTEXT = [("vocab_grammar_coverage_cognitive", "best curated set: vocab + grammar_coverage + cognitive (new)"),
                   ("original_all", "curated reference: all (old)"), ("surface", "curated reference: surface (new)")]


def features(emb, layer):
    return emb[:, 1:, :].mean(axis=1) if layer == "mean" else emb[:, layer, :]


def name_of(layer):
    return "mean of layers 1-12" if layer == "mean" else (f"layer {layer} (embeddings)" if layer == 0 else f"layer {layer}")


def curated_context(train, model="gradient boosting"):
    """The curated rows for context, read from the curated raw run (empty if it is not there). `model` is a heading of that run."""
    path = CURATED_RUNS / f"{train}_main.md"
    if not path.exists():
        return []
    rows = {r[0]: r for r in table(path.read_text(encoding="utf-8"), f"## test: {model}")}
    short = "ridge" if model == "ridge regression" else "gradient boosting"
    return [(f"{label} ({short})", rows[k]) for k, label in CURATED_CONTEXT if k in rows]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", default=embeddings.DEFAULT_MODEL)
    args = ap.parse_args()

    emb = {s: embeddings.load(args.model, s) for s in ("train", "test")}
    train_df, test_df = load_split("train"), load_split("test")
    y_test = test_df["label"].to_numpy()
    n_layers = emb["train"].shape[1]
    layers = list(range(n_layers)) + ["mean"]
    results, preds = {}, {}
    for train, _ in TRAIN_SETS.items():
        mask = train_mask(train_df, train)
        y_train = train_df["label"].to_numpy()[mask]
        for layer in layers:
            model = make_pipeline(StandardScaler(), RidgeCV(alphas=np.logspace(-1, 4, 11)))
            model.fit(features(emb["train"], layer)[mask], y_train)
            pred = model.predict(features(emb["test"], layer))
            results[(train, layer)] = {**metrics(y_test, pred), "ci": ci(bootstrap_mae(y_test, pred)), "alpha": float(model[-1].alpha_)}
            preds[(train, layer)] = pred
            predictions.save("bert", "ridge", "mean_layers_1_12" if layer == "mean" else f"layer_{layer:02d}", train, y_test, pred)
            print(f"{train} {name_of(layer):22s} MAE {results[(train, layer)]['mae']:.3f}", flush=True)
        dummies = {"most common label": train_df["label"][mask].mode().iloc[0], "median label": train_df["label"][mask].median()}
        results[(train, "dummy")] = {k: float(np.abs(v - y_test).mean()) for k, v in dummies.items()}

    def best(train):
        return min(layers, key=lambda l: results[(train, l)]["mae"])

    def row(train, layer):
        r = results[(train, layer)]
        return [f"**{name_of(layer)}**" if layer == best(train) else name_of(layer), f"{r['mae']:.3f} [{r['ci'][0]:.3f}, {r['ci'][1]:.3f}]", steps(r["mae"]),
                pct(r["accuracy"]), pct(r["accuracy_1step"])]

    header = "| layer | average miss (MAE) [95% interval] | in label steps | exactly right | within one step |\n|---|---|---:|---:|---:|"
    L = ["# Frozen BERT embeddings, layer by layer", "",
         f"Generated by `bert_based/run_layers.py`. Model: `{args.model}`, frozen (nothing is fine-tuned).", "", "## Summary", ""]
    for train, desc in TRAIN_SETS.items():
        b = best(train)
        gb = next((r[3] for lbl, r in curated_context(train) if lbl.startswith("best curated")), None)
        rd = next((r[3] for lbl, r in curated_context(train, "ridge regression") if lbl.startswith("best curated")), None)
        best_cur = f" The best curated feature set misses by {gb} with gradient boosting and by {rd} with ridge regression (the model used here)." if gb and rd else ""
        L.append(f"- Trained on {desc}: the best layer is **{name_of(b)}** with an average miss of **{results[(train, b)]['mae']:.3f}** "
                 f"(layer 0: {results[(train, 0)]['mae']:.3f}, layer 12: {results[(train, 12)]['mae']:.3f}; a constant guess: "
                 f"{results[(train, 'dummy')]['most common label']:.3f}).{best_cur}")
    L += ["", "## How to read the numbers", "",
          "- **Average miss (MAE)**: average distance between predicted and true label; smaller is better. One label step is 0.5.",
          "- **Exactly right / within one step**: the prediction, rounded to the nearest half step, equals the label / is off by at most 0.5.",
          "- **95% interval**: from resampling the 865 test texts; overlapping intervals may be noise.",
          "- Layer 0 is the word-piece embedding layer, before any transformer layer; layers 1 to 12 are the transformer layers.", "",
          "## Setup", "",
          f"- Model `{args.model}`, 12 transformer layers, 768 dimensions. Frozen: the embeddings are computed once (`bert_based/embeddings.py`).",
          f"- Each text is cut into windows of at most {embeddings.WINDOW} word-pieces; for each layer the hidden states of all word-pieces of the text are averaged "
          "(one vector of 768 numbers per text and layer).",
          "- Regressor: ridge regression on standardised embeddings, regularisation chosen by leave-one-out cross-validation on the training texts.",
          "- Test set: the same 865 real-Finnish texts as in the curated results, so the numbers are comparable with `curated_features/modeling/reports/RESULTS.md`.", "",
          "## Results", ""]
    for train, desc in TRAIN_SETS.items():
        L += [f"### Trained on {desc}", "", header]
        L += ["| " + " | ".join(row(train, layer)) + " |" for layer in layers]
        for label, r in curated_context(train) + curated_context(train, "ridge regression"):
            L.append(f"| *{label}* | {r[3]} {r[4]} | {steps(r[3])} | {r[5]} | {r[6]} |")
        d = results[(train, "dummy")]
        L += [f"| *constant guess ({k})* | {v:.3f} | {steps(v)} | | |" for k, v in d.items()] + [""]
    b = best("train_native")
    L += [f"### Confusion matrix of the best layer ({name_of(b)}, trained on real-Finnish rows)", "",
          "Each row is the true label, each column the predicted label (rounded to the nearest half step). A row adds up to 100%; the **bold** cell is the share predicted exactly right.", ""]
    L += confusion_md(y_test, preds[("train_native", b)])
    L += ["", "## Reproduce", "", "```", "python bert_based/embeddings.py", "python bert_based/run_layers.py", "```", ""]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(L), encoding="utf-8")
    print("report ->", REPORT)


if __name__ == "__main__":
    main()
