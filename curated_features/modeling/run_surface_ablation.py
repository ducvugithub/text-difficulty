"""Is the best model biased towards surface measures? The best feature set without them.

The cognitive features (sentence length, and the old parse features that include tokens per sentence) carry more than half of the best model's importance, and the
labels follow word and sentence length closely. This removes them, step by step, and compares:

  the best set                                  vocab + grammar concepts + cognitive
  minus the sentence-length features            (the old parse features stay)
  minus all cognitive features                  vocab + grammar concepts
  minus the length-like vocab features too      also without mean word length, share of long words, number of distinct lemmas, number of compounds

Each variant is graded on the 865 real-Finnish test texts (trained on the real-Finnish train rows and on all train rows) and on the FI source alone (trained on the FI
train rows), where the source cannot explain the label. Gradient boosting. The last variant is also checked for what it relies on.

    python curated_features/modeling/run_surface_ablation.py        writes curated_features/modeling/reports/SURFACE_ABLATION.md
"""
import sys
import warnings
from pathlib import Path

import numpy as np
from sklearn.ensemble import HistGradientBoostingRegressor

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # repo root
from core.dataset import TRAIN_SETS, load_split, train_mask  # noqa: E402
from core.evaluate import bootstrap_mae, ci  # noqa: E402
from core.reporting import md_table  # noqa: E402
from curated_features.modeling.run_feature_importance import shuffled_mae  # noqa: E402
from curated_features.utils import registry  # noqa: E402
from curated_features.utils.feature_store import feature_table  # noqa: E402

VOCAB = [("vocab", "freq"), ("vocab", "lexical")]
CONCEPTS = [("grammar", "coverage_concepts")]
PARSE, SENTENCE = ("cognitive", "parse_old"), ("cognitive", "sentence_length")
LENGTH_LIKE = ["avg_word_length", "long_word_ratio", "n_unique_lemmas", "n_compound_tokens"]
SETS = {
    "the best set (vocab + concepts + cognitive)": {"signals": VOCAB + CONCEPTS + [PARSE, SENTENCE]},
    "minus the sentence-length features": {"signals": VOCAB + CONCEPTS + [PARSE]},
    "minus all cognitive features": {"signals": VOCAB + CONCEPTS},
    "minus all cognitive and the length-like vocab features": {"signals": VOCAB + CONCEPTS, "exclude": LENGTH_LIKE},
    "reference: the 4 surface measures only": {"surface": True},
}
REPORT = Path(__file__).resolve().parent / "reports" / "SURFACE_ABLATION.md"


def gbm():
    return HistGradientBoostingRegressor(max_iter=300, learning_rate=0.05, random_state=0)


def fit_predict(spec, train_rows, test_rows):
    """Fit on the chosen rows of the train split, predict the chosen rows of the test split."""
    tr, te = feature_table("train", spec), feature_table("test", spec)
    cols = list(tr[0].columns)
    model = gbm().fit(tr[0].to_numpy()[train_rows(tr[1])], tr[1]["label"].to_numpy()[train_rows(tr[1])])
    rows = test_rows(te[1])
    return model, len(cols), te[0].reindex(columns=cols, fill_value=0.0).to_numpy(), rows


def cell(y, p):
    lo, hi = ci(bootstrap_mae(y, p))
    return f"{np.abs(p - y).mean():.3f} [{lo:.3f}, {hi:.3f}]"


def main():
    warnings.filterwarnings("ignore")
    y_test = load_split("test")["label"].to_numpy()
    everything = lambda d: np.ones(len(d), bool)  # noqa: E731
    is_fi = lambda d: (d["source"] == "FI").to_numpy()  # noqa: E731
    fi_native = lambda d: is_fi(d) & (d["origine"] == "Real").to_numpy()  # noqa: E731
    results, n_feat, last = {}, {}, None
    for name, spec in SETS.items():
        row = {}
        for train in TRAIN_SETS:
            model, n, X, rows = fit_predict(spec, lambda d, t=train: train_mask(d, t), everything)
            row[train] = (y_test, model.predict(X))
            last = (name, model, X) if name.startswith("minus all cognitive and") and train == "train_native" else last
        model, n, X, rows = fit_predict(spec, fi_native, is_fi)
        row["fi"] = (y_test[rows], model.predict(X[rows]))
        results[name], n_feat[name] = row, n
    train_df = load_split("train")
    const = {"train_native": float(np.median(train_df["label"][train_mask(train_df, "train_native")])), "train_all": float(np.median(train_df["label"])),
             "fi": float(np.median(train_df["label"][fi_native(train_df)]))}
    fi_y = y_test[is_fi(load_split("test"))]

    best, no_cog = "the best set (vocab + concepts + cognitive)", "minus all cognitive features"
    strict = "minus all cognitive and the length-like vocab features"
    mae = lambda k, t: float(np.abs(results[k][t][1] - results[k][t][0]).mean())  # noqa: E731
    L = ["# Is the best model biased towards surface measures? The best set without them", "",
         "Generated by `curated_features/modeling/run_surface_ablation.py`. The cognitive features (sentence length, and the old parse features that include tokens per sentence) "
         "carry more than half of the best model's importance, and the labels follow word and sentence length closely. Here they are removed step by step. "
         "Gradient boosting; test = the 865 real-Finnish test texts.", "", "## Summary", "",
         f"- The best set misses by {mae(best, 'train_native'):.3f} on the test set (trained on real-Finnish rows). Without all cognitive features: {mae(no_cog, 'train_native'):.3f}; "
         f"also without the length-like vocab features: {mae(strict, 'train_native'):.3f}.",
         f"- On `FI` alone (labels vary, the source cannot explain them), trained on FI rows: {mae(best, 'fi'):.3f} for the best set, {mae(no_cog, 'fi'):.3f} without the cognitive features, "
         f"{mae(strict, 'fi'):.3f} without the length-like vocab features too; a constant guess gives {np.abs(const['fi'] - fi_y).mean():.3f} and the 4 surface measures "
         f"{mae('reference: the 4 surface measures only', 'fi'):.3f}.", "",
         "## How to read the numbers", "",
         "- **Average miss (MAE)** with a 95% interval from resampling the texts; smaller is better. One label step is 0.5.",
         "- **FI only** is graded on the 310 FI test texts after training on the FI train rows only (729 texts): the one source whose labels vary, so recognising the source does not help.",
         "- **Length-like vocab features**: `avg_word_length`, `long_word_ratio`, `n_unique_lemmas` (grows with text length) and `n_compound_tokens` (a count).", "",
         "## Results", ""]
    header = ["feature set", "features", f"test, trained on {TRAIN_SETS['train_native']}", f"test, trained on {TRAIN_SETS['train_all']}", "FI only, trained on FI rows"]
    rows = [[name, n_feat[name], cell(*results[name]["train_native"]), cell(*results[name]["train_all"]), cell(*results[name]["fi"])] for name in SETS]
    rows.append(["reference: constant guess (median label)", 0, f"{np.abs(const['train_native'] - y_test).mean():.3f}", f"{np.abs(const['train_all'] - y_test).mean():.3f}",
                 f"{np.abs(const['fi'] - fi_y).mean():.3f}"])
    L += md_table(header, rows) + [""]

    name, model, X = last
    index = {n: i for i, n in enumerate(feature_table("test", SETS[name])[0].columns)}
    groups = {"vocab: word frequency bins": registry.make("vocab", "freq").feature_names,
              "vocab: word form (without the length-like features)": [n for n in registry.make("vocab", "lexical").feature_names if n not in LENGTH_LIKE],
              "grammar concepts (one feature per concept)": registry.make("grammar", "coverage_concepts").feature_names}
    rng = np.random.default_rng(0)
    base = float(np.abs(model.predict(X) - y_test).mean())
    imp = sorted(((g, len([n for n in ns if n in index]), (shuffled_mae(model, X, y_test, [index[n] for n in ns if n in index], rng) - base)) for g, ns in groups.items()),
                 key=lambda r: -r[2].mean())
    L += ["## What the strictest variant relies on", "",
          f"Permutation importance by group for the variant without the cognitive and length-like features (trained on {TRAIN_SETS['train_native']}, test miss {base:.3f}): "
          "the values of a group are scrambled between the test texts and the average miss grows by the amount shown.", ""]
    L += md_table(["group", "features", "average miss grows by", "spread over 5 scrambles"], [[g, n, f"{v.mean():.3f}", f"±{v.std():.3f}"] for g, n, v in imp])
    L += ["", "## Reproduce", "", "```", "python curated_features/modeling/run_surface_ablation.py", "```", ""]
    REPORT.write_text("\n".join(L), encoding="utf-8")
    print("report ->", REPORT)


if __name__ == "__main__":
    main()
