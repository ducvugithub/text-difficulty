"""Do the syllabus topics add anything once the grammar concepts are there? Concepts alone, topics alone, and both, on their own and inside the best feature set.

A topic is a combination of concepts taught together, so the concept features may already hold what the topic features say. Gradient boosting, graded on the same 865
real-Finnish test texts as the other experiments, for both training sets.

    python curated_features/modeling/run_grammar_concepts_vs_topics.py        writes curated_features/modeling/reports/GRAMMAR_CONCEPTS_VS_TOPICS.md
"""
import sys
import warnings
from pathlib import Path

import numpy as np
from sklearn.ensemble import HistGradientBoostingRegressor

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # repo root
from core.dataset import TRAIN_SETS, load_split, train_mask  # noqa: E402
from core.evaluate import bootstrap_mae, ci, metrics  # noqa: E402
from core.reporting import md_table, pct, steps, mae_fmt, PCT_NOTE  # noqa: E402
from curated_features.utils.feature_store import feature_table  # noqa: E402

CONCEPTS, TOPICS = [("grammar", "coverage_concepts")], [("grammar", "coverage_topics")]
VOCAB, COGNITIVE = [("vocab", "freq"), ("vocab", "lexical")], [("cognitive", "parse_old"), ("cognitive", "sentence_length")]
SETS = {  # name -> signals
    "grammar: concepts only": CONCEPTS, "grammar: topics only": TOPICS, "grammar: concepts + topics": CONCEPTS + TOPICS,
    "vocab + concepts + cognitive": VOCAB + CONCEPTS + COGNITIVE, "vocab + topics + cognitive": VOCAB + TOPICS + COGNITIVE,
    "vocab + concepts + topics + cognitive (the earlier best set)": VOCAB + CONCEPTS + TOPICS + COGNITIVE,
}
REPORT = Path(__file__).resolve().parent / "reports" / "GRAMMAR_CONCEPTS_VS_TOPICS.md"


def test_predictions(name, train):
    spec = {"signals": SETS[name]}
    tr, te = feature_table("train", spec), feature_table("test", spec)
    cols = list(tr[0].columns)
    mask = train_mask(tr[1], train)
    model = HistGradientBoostingRegressor(max_iter=300, learning_rate=0.05, random_state=0).fit(tr[0][mask].to_numpy(), tr[1]["label"].to_numpy()[mask])
    return len(cols), model.predict(te[0].reindex(columns=cols, fill_value=0.0).to_numpy())


def main():
    warnings.filterwarnings("ignore")
    y = load_split("test")["label"].to_numpy()
    L = ["# Grammar concepts or syllabus topics: does one cover the other?", "",
         "Generated by `curated_features/modeling/run_grammar_concepts_vs_topics.py`. A syllabus topic is a combination of grammar concepts taught together, so the concept features "
         "may already hold what the topic features say. Gradient boosting, graded on the same 865 real-Finnish test texts as the other results.", "", "## Summary", "", "@@summary@@", "",
         "## How to read the numbers", "",
         "- **Average miss (MAE)**: average distance between predicted and true label; smaller is better. One label step is 0.5. " + PCT_NOTE + " **95% interval**: from resampling the test texts.",
         "- Each feature is one concept's (or topic's) share of the text. The earlier best set also contains the vocab and cognitive features. Because of this result the grammar features are now the concept features only, and `vocab + concepts + cognitive` is the best set.", ""]
    summary = []
    for train, desc in TRAIN_SETS.items():
        res = {name: test_predictions(name, train) for name in SETS}
        rows = []
        for name, (n, p) in res.items():
            m = metrics(y, p)
            lo, hi = ci(bootstrap_mae(y, p))
            rows.append([name, n, f"{mae_fmt(m['mae'])} [{lo:.3f}, {hi:.3f}]", steps(m["mae"]), pct(m["accuracy"]), pct(m["accuracy_1step"])])
        L += [f"## Trained on {desc}", ""] + md_table(["feature set", "features", "average miss (MAE) [95% interval]", "in label steps", "exactly right", "within one step"], rows) + [""]
        best = res["vocab + concepts + topics + cognitive (the earlier best set)"][1]
        for name in ("vocab + concepts + cognitive", "vocab + topics + cognitive"):
            diff = bootstrap_mae(y, res[name][1]) - bootstrap_mae(y, best)
            lo, hi = ci(diff)
            summary.append(f"- Trained on {desc}: `{name}` against the earlier best set (concepts and topics): {diff.mean():+.3f} [{lo:+.3f}, {hi:+.3f}] "
                           + ("(no clear difference)." if lo <= 0 <= hi else ("(better)." if hi < 0 else "(worse).")))
    L = [("\n".join(summary) if line == "@@summary@@" else line) for line in L]
    L += ["## Reproduce", "", "```", "python curated_features/modeling/run_grammar_concepts_vs_topics.py", "```", ""]
    REPORT.write_text("\n".join(L), encoding="utf-8")
    print("report ->", REPORT)


if __name__ == "__main__":
    main()
